// Generates an array from 0 to max so we can fallback
export function getGenericFlavor(word: string, usageCount: number): string | null {
  const list = GENERIC_FLAVOR_PROGRESSION[word];
  if (!list) return null;
  const index = Math.min(usageCount, list.length - 1);
  return list[index];
}

export function getMonsterFlavor(monsterName: string, interactionCount: number): string | null {
  const genericMonsterResponses = [
    'Grrr... Que som é esse que você faz?',
    'Acha que pode me confundir com palavras?',
    'Pare de tagarelar e lute!',
    'Você vai virar meu almoço logo, logo!',
    'Seu fim está próximo, herói de araque...',
    'Eu vou esmagar você e o seu livrinho mágico!'
  ];

  const list = MONSTER_SPECIFIC_FLAVORS[monsterName];
  if (!list) {
    const index = Math.min(interactionCount, genericMonsterResponses.length - 1);
    return genericMonsterResponses[index];
  }
  
  const index = Math.min(interactionCount, list.length - 1);
  return list[index];
}
